        public static string GetWeatherCondition(string code) {
            if (string.IsNullOrEmpty(code)) code = "PartlyCloudy";
            string key = "Weather." + code;
            return T(key);
        }

        public static string T(string key, params object[] args) {
            if (string.IsNullOrEmpty(key)) return "";

            Dictionary<string, string> dict;
            string val = null;

            if (_translations.TryGetValue(_currentLang, out dict) && dict.TryGetValue(key, out val)) {
                // found
            } else if (_translations.TryGetValue(LANG_ZH_TW, out dict) && dict.TryGetValue(key, out val)) {
                // fallback to zh-TW
            } else {
                val = key;
            }

            if (args != null && args.Length > 0 && !string.IsNullOrEmpty(val)) {
                try {
                    return string.Format(val, args);
                } catch {
                    return val;
                }
            }
            return val;
        }

