        public static event Action LanguageChanged;

        public static string CurrentLanguage {
            get { return _currentLang; }
            set {
                string normalized = NormalizeLanguageCode(value);
                if (_currentLang != normalized) {
                    _currentLang = normalized;
                    if (LanguageChanged != null) {
                        LanguageChanged.Invoke();
                    }
                }
            }
        }

        public static System.Globalization.CultureInfo CurrentCulture {
            get {
                try {
                    return System.Globalization.CultureInfo.GetCultureInfo(_currentLang);
                } catch {
                    return System.Globalization.CultureInfo.InvariantCulture;
                }
            }
        }

        public static string NormalizeLanguageCode(string lang) {
            if (string.IsNullOrWhiteSpace(lang)) return LANG_ZH_TW;
            lang = lang.Trim();
            if (lang.StartsWith("zh-CN", StringComparison.OrdinalIgnoreCase) || lang.StartsWith("zh-Hans", StringComparison.OrdinalIgnoreCase)) return LANG_ZH_CN;
            if (lang.StartsWith("zh", StringComparison.OrdinalIgnoreCase)) return LANG_ZH_TW;
            if (lang.StartsWith("ja", StringComparison.OrdinalIgnoreCase)) return LANG_JA_JP;
            if (lang.StartsWith("en", StringComparison.OrdinalIgnoreCase)) return LANG_EN_US;
            if (lang.StartsWith("ko", StringComparison.OrdinalIgnoreCase)) return LANG_KO_KR;
            if (lang.StartsWith("es", StringComparison.OrdinalIgnoreCase)) return LANG_ES_ES;
            if (lang.StartsWith("fr", StringComparison.OrdinalIgnoreCase)) return LANG_FR_FR;
            if (lang.StartsWith("de", StringComparison.OrdinalIgnoreCase)) return LANG_DE_DE;
            if (lang.StartsWith("pt", StringComparison.OrdinalIgnoreCase)) return LANG_PT_BR;
            if (lang.StartsWith("ru", StringComparison.OrdinalIgnoreCase)) return LANG_RU_RU;
            if (lang.StartsWith("it", StringComparison.OrdinalIgnoreCase)) return LANG_IT_IT;
            if (lang.StartsWith("vi", StringComparison.OrdinalIgnoreCase)) return LANG_VI_VN;
            return LANG_ZH_TW;
        }

        public static string FormatDate(DateTime dt) {
            try {
                if (_currentLang == LANG_EN_US) return dt.ToString("MMM d, dddd", CurrentCulture);
                if (_currentLang == LANG_JA_JP) return dt.ToString("M月d日 (ddd)", CurrentCulture);
                if (_currentLang == LANG_KO_KR) return dt.ToString("M월 d일 (ddd)", CurrentCulture);
                if (_currentLang == LANG_ZH_CN || _currentLang == LANG_ZH_TW) return dt.ToString("M月d日 dddd", CurrentCulture);
                return dt.ToString("d MMM, dddd", CurrentCulture);
            } catch {
                return dt.ToString("M/d");
            }
        }

        public static string FormatCompactDate(DateTime dt) {
            try {
                if (_currentLang == LANG_EN_US) return dt.ToString("MMM d ddd", CurrentCulture);
                if (_currentLang == LANG_JA_JP) return dt.ToString("M月d日 (ddd)", CurrentCulture);
                if (_currentLang == LANG_KO_KR) return dt.ToString("M월 d일 (ddd)", CurrentCulture);
                if (_currentLang == LANG_ZH_CN || _currentLang == LANG_ZH_TW) return dt.ToString("M月d日 ddd", CurrentCulture);
                return dt.ToString("d MMM ddd", CurrentCulture);
            } catch {
                return dt.ToString("M/d");
            }
        }

